-- Tabela tb_administrador
CREATE TABLE tb_administrador (
    id_administrador bigint GENERATED BY DEFAULT AS IDENTITY,
    data_assinatura date,
    data_nasc date NOT NULL,
    email character varying(255) NOT NULL,
    nome character varying(255) NOT NULL,
    pin integer NOT NULL,
    premium boolean,
    senha character varying(255) NOT NULL,
    sexo character varying(255) NOT NULL,
    telefone character varying(255) NOT NULL,
    valor_mensalidade real,
    CONSTRAINT pk_administrador PRIMARY KEY (id_administrador),
    CONSTRAINT uk_administrador_telefone UNIQUE (telefone),
    CONSTRAINT uk_administrador_email UNIQUE (email)
);

-- Tabela tb_backupmanager
CREATE TABLE tb_backupmanager (
    id_back_up bigint GENERATED BY DEFAULT AS IDENTITY,
    caminho_backup character varying(255),
    data_ultimo_backup date,
    fk_administrador bigint,
    CONSTRAINT pk_backupmanager PRIMARY KEY (id_back_up),
    CONSTRAINT uk_backupmanager_fk_administrador UNIQUE (fk_administrador)
);

-- Tabela tb_usuario
CREATE TABLE tb_usuario (
    id_usuario bigint GENERATED BY DEFAULT AS IDENTITY,
    biografia text,
    data_nasc_aut date NOT NULL,
    nivel_autismo character varying(255),
    nome character varying(255) NOT NULL,
    sexo character varying(255),
    voz boolean,
    fk_administrador bigint,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario)
);

-- Tabela tb_tiradesentenca
CREATE TABLE tb_tiradesentenca (
    id_tira_de_sentenca bigint GENERATED BY DEFAULT AS IDENTITY,
    texto_formatado character varying(255),
    fk_usuario bigint,
    CONSTRAINT pk_tiradesentenca PRIMARY KEY (id_tira_de_sentenca),
    CONSTRAINT uk_tiradesentenca_fk_usuario UNIQUE (fk_usuario)
);

-- Tabela tb_botao
CREATE TABLE tb_botao (
    id_botao bigint GENERATED BY DEFAULT AS IDENTITY,
    audio_fem character varying(255),
    audio_fem_public_id character varying(255),
    audio_mas character varying(255),
    audio_mas_public_id character varying(255),
    audio_personalizado character varying(255),
    audio_personalizado_public_id character varying(255),
    cor_fundo character varying(255),
    cor_fundo_legenda character varying(7),
    cor_legenda character varying(7),
    exibir_legenda boolean NOT NULL,
    foto character varying(255),
    foto_public_id character varying(255),
    legenda character varying(255),
    oculto boolean,
    tamanho_botao integer,
    fk_administrador bigint,
    fk_tira_de_sentenca bigint,
    fk_usuario bigint,
    CONSTRAINT pk_botao PRIMARY KEY (id_botao)
);

-- Tabela tb_categoria
CREATE TABLE tb_categoria (
    id_categoria bigint GENERATED BY DEFAULT AS IDENTITY,
    foto_cat character varying(255),
    foto_cat_public_id character varying(255),
    nome character varying(255) NOT NULL,
    posicao_cat integer,
    fk_administrador bigint,
    fk_usuario bigint,
    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria)
);

-- Tabela tb_botao_categoria
